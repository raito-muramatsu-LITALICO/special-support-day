  $("#sceneBody").textContent = scene.body;
  $("#painTags").innerHTML = scene.tags.map((tag) => `<span class="tag">${tag}</span>`).join("");
  $("#choices").innerHTML = "";
  $("#choices").classList.remove("hidden");
  $("#decisionReflection").classList.add("hidden");
  $("#decisionNote").value = "";

